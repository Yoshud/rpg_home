"""The Alembic migrations: they build the schema of the ORM tables, the app upgrades on open,
and the `alembic` command line works on the configured data folder.

Several tests run throwaway revisions: a copy of `migrations/` in a temporary folder plus one
extra revision file, with `db.MIGRATIONS_DIR` pointed at it."""

import asyncio
import shutil
import sqlite3
import subprocess
import sys
from pathlib import Path

import pytest
from alembic import command
from alembic.script import ScriptDirectory
from alembic.util import AutogenerateDiffsDetected
from sqlalchemy import Column, Integer, Table
from sqlalchemy.exc import IntegrityError

from rpghome.managers import library
from rpghome.repositories import db
from rpghome.repositories.catalog import Catalog
from rpghome.repositories.tables import Base

ROOT = Path(__file__).parents[2]


def _head() -> str:
    return ScriptDirectory.from_config(db.alembic_config()).get_current_head()


def _version(path: Path) -> str:
    with sqlite3.connect(path) as conn:
        return conn.execute("SELECT version_num FROM alembic_version").fetchone()[0]


def _tables(path: Path) -> set[str]:
    with sqlite3.connect(path) as conn:
        rows = conn.execute("SELECT name FROM sqlite_master WHERE type = 'table'").fetchall()
    return {r[0] for r in rows}


async def test_upgrade_creates_the_schema_and_is_idempotent(tmp_path):
    path = tmp_path / "data" / db.DB_NAME
    await db.upgrade(path)
    assert _version(path) == _head()
    assert _tables(path) == {"alembic_version", *Base.metadata.tables}
    await db.upgrade(path)  # at head already: nothing to do
    assert _version(path) == _head()
    with sqlite3.connect(path) as conn:
        assert conn.execute("PRAGMA journal_mode").fetchone()[0] == "wal"


def _with_connection(connection):
    config = db.alembic_config()
    config.attributes["connection"] = connection
    return config


async def _run(path: Path, alembic_command) -> None:
    """An Alembic command on a connection of the app's engine (the connection-sharing recipe)."""
    engine = db.create_engine(path, foreign_keys=False)
    try:
        async with engine.begin() as conn:
            await conn.run_sync(lambda c: alembic_command(_with_connection(c)))
    finally:
        await engine.dispose()


async def _check(path: Path) -> None:
    await _run(path, command.check)


async def test_migrations_match_the_orm_tables(tmp_path):
    """`alembic check`: autogenerate finds no difference between head and tables.py."""
    path = tmp_path / db.DB_NAME
    await db.upgrade(path)
    await _check(path)


async def test_check_notices_a_table_without_migration(tmp_path):
    path = tmp_path / db.DB_NAME
    await db.upgrade(path)
    extra = Table("extra", Base.metadata, Column("x", Integer, primary_key=True))
    try:
        with pytest.raises(AutogenerateDiffsDetected, match="extra"):
            await _check(path)
    finally:
        Base.metadata.remove(extra)


async def test_downgrade_and_upgrade_again(tmp_path):
    path = tmp_path / db.DB_NAME
    await db.upgrade(path)
    await _run(path, lambda config: command.downgrade(config, "base"))
    assert _tables(path) == {"alembic_version"}
    await db.upgrade(path)
    assert _tables(path) == {"alembic_version", *Base.metadata.tables}


def test_alembic_command_line_uses_the_settings(env):
    """`alembic upgrade head` / `alembic check` from the repo, on RPGHOME_ARTIFACTS."""
    for args in (["upgrade", "head"], ["check"], ["current"]):
        r = subprocess.run(
            [sys.executable, "-m", "alembic", *args], cwd=ROOT, capture_output=True, text=True
        )
        assert r.returncode == 0, r.stderr
    assert "(head)" in r.stdout
    assert _version(env / "artifacts" / db.DB_NAME) == _head()


# -- throwaway revisions ------------------------------------------------------------------------


def _scripts_with(tmp_path: Path, revision: str, upgrade_body: str) -> Path:
    """`migrations/` copied to a temporary folder, plus one revision on top of head."""
    scripts = tmp_path / "scripts"
    shutil.copytree(ROOT / "migrations", scripts, ignore=shutil.ignore_patterns("__pycache__"))
    (scripts / "versions" / f"{revision}.py").write_text(f'''"""throwaway {revision}

Revision ID: {revision}
Revises: {_head()}

"""

from collections.abc import Sequence

import sqlalchemy as sa
from alembic import op

revision: str = "{revision}"
down_revision: str | None = "{_head()}"
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None


def upgrade() -> None:
{upgrade_body}


def downgrade() -> None:
    pass
''')
    return scripts


def _seed(path: Path) -> None:
    """A clip with two tags, in a pool."""
    with sqlite3.connect(path) as conn:
        conn.execute(
            "INSERT INTO clips (id, path, kind, status, source, license, title, loopable,"
            " notes, search_text) VALUES ('c1', 'a.wav', 'bed', 'review', 'other',"
            " 'shareable', 't', 0, '', 't')"
        )
        conn.execute("INSERT INTO clip_tags (clip_id, tag) VALUES ('c1', 'x'), ('c1', 'y')")
        conn.execute("INSERT INTO pools (name, description) VALUES ('p1', '')")
        conn.execute("INSERT INTO clip_pools (clip_id, pool) VALUES ('c1', 'p1')")


async def test_upgrade_runs_with_foreign_keys_off(tmp_path, monkeypatch):
    """A batch migration recreates `clips` (drop + rename). With foreign keys on, the ON DELETE
    CASCADE of clip_tags / clip_pools would delete the rows that refer to it during the swap;
    the upgrade runs with foreign keys off, so they survive."""
    path = tmp_path / db.DB_NAME
    await db.upgrade(path)
    _seed(path)
    scripts = _scripts_with(
        tmp_path,
        "0002_swap_clips",
        '    with op.batch_alter_table("clips") as batch_op:\n'
        '        batch_op.drop_column("sha256")',
    )
    monkeypatch.setattr(db, "MIGRATIONS_DIR", scripts)
    await db.upgrade(path)
    with sqlite3.connect(path) as conn:
        version = conn.execute("SELECT version_num FROM alembic_version").fetchone()[0]
        assert version == "0002_swap_clips"
        assert conn.execute("SELECT COUNT(*) FROM clips").fetchone()[0] == 1
        assert conn.execute("SELECT tag FROM clip_tags ORDER BY tag").fetchall() == [("x",), ("y",)]
        assert conn.execute("SELECT COUNT(*) FROM clip_pools").fetchone()[0] == 1


async def test_normal_connections_enforce_foreign_keys(tmp_path):
    """The upgrade may switch foreign keys off, but every normal connection has them on."""
    path = tmp_path / db.DB_NAME
    await db.upgrade(path)
    engine = db.create_engine(path)
    try:
        async with engine.begin() as conn:
            assert (await conn.exec_driver_sql("PRAGMA foreign_keys")).scalar() == 1
            with pytest.raises(IntegrityError, match="FOREIGN KEY"):
                await conn.exec_driver_sql(
                    "INSERT INTO clip_tags (clip_id, tag) VALUES ('ghost', 't')"
                )
    finally:
        await engine.dispose()


async def test_upgrade_reports_rows_left_dangling(tmp_path, monkeypatch):
    """Without `PRAGMA foreign_key_check` this migration would pass silently, leaving clip_pools
    rows that point at a deleted pool."""
    path = tmp_path / db.DB_NAME
    await db.upgrade(path)
    _seed(path)
    scripts = _scripts_with(tmp_path, "0002_clear_pools", '    op.execute("DELETE FROM pools")')
    monkeypatch.setattr(db, "MIGRATIONS_DIR", scripts)
    with pytest.raises(db.DatabaseError, match="broke foreign keys"):
        await db.upgrade(path)
    # the failed upgrade is rolled back: the pool and the reference are still there
    with sqlite3.connect(path) as conn:
        assert conn.execute("SELECT name FROM pools").fetchall() == [("p1",)]
        assert conn.execute("SELECT COUNT(*) FROM clip_pools").fetchone()[0] == 1


async def test_failed_migration_leaves_no_half_applied_schema(tmp_path, monkeypatch):
    """The upgrade is transactional: a migration that fails halfway leaves the old schema and
    the old version, not a half-applied one."""
    path = tmp_path / db.DB_NAME
    await db.upgrade(path)
    before, head = _tables(path), _head()
    scripts = _scripts_with(
        tmp_path,
        "0002_half",
        '    op.create_table("half_applied", sa.Column("x", sa.Integer, primary_key=True))\n'
        '    op.execute("SELECT syntax_error((")',
    )
    monkeypatch.setattr(db, "MIGRATIONS_DIR", scripts)
    with pytest.raises(db.DatabaseError, match="migration failed"):
        await db.upgrade(path)
    assert _tables(path) == before
    assert _version(path) == head


async def test_two_imports_at_once_take_turns(tmp_path, sound_gen, needs_ffmpeg):
    """Two writers, two catalogs, one import lock: the flock and the SQLite write lock serialize
    them; both finish, nothing is imported twice."""
    data = tmp_path / "data"
    lock = tmp_path / "state" / "locks" / library.LOCK_NAME
    async with Catalog(data) as c1, Catalog(data) as c2:
        reports = await asyncio.gather(
            library.import_sound_gen(sound_gen, c1, lock_path=lock),
            library.import_sound_gen(sound_gen, c2, lock_path=lock),
        )
    assert sorted(len(r.created) for r in reports) == [0, 10]
    assert sorted(len(r.unchanged) for r in reports) == [0, 10]
    async with Catalog(data) as cat:
        assert len(await cat.all()) == 10
